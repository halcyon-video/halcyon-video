/** Simple string hash for deterministic selection. */
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Returns a genre-appropriate review snippet for a given movie.
 * Uses movie ID (or title) for deterministic selection across re-renders.
 */
export function getReviewSnippetForMovie(movie: { id?: string; title?: string; genres: string[] }): string {
  const g = (movie.genres || []).map((x) => x.toLowerCase());
  const has = (...names: string[]) => names.some((n) => g.includes(n));
  const seedKey = movie.id || movie.title || 'default-movie';
  const seed = hashString(seedKey);

  let pool: string[] = [];

  // Check multi-genre combinations first
  if (has('horror') && has('comedy')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.HORROR_COMEDY;
  } else if (has('action', 'adventure') && has('sci-fi', 'science fiction')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.ACTION_SCI_FI;
  } else if (has('action', 'adventure') && has('comedy')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.ACTION_COMEDY;
  } else if (has('horror') && has('sci-fi', 'science fiction')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.HORROR_SCI_FI;
  } else if (has('sci-fi', 'science fiction') && has('thriller', 'suspense', 'mystery')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.SCI_FI_THRILLER;
  } else if (has('romance') && has('comedy')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.ROMANTIC_COMEDY;
  } else if (has('drama') && has('thriller', 'suspense', 'crime')) {
    pool = REVIEW_SNIPPETS_BY_GENRE.DRAMA_THRILLER;
  }

  // Fallback to single primary genre if no multi-genre pool matched
  if (!pool || pool.length === 0) {
    if (has('horror')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.HORROR;
    } else if (has('sci-fi', 'science fiction', 'fantasy')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.SCI_FI;
    } else if (has('action', 'adventure', 'war', 'western', 'martial arts')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.ACTION;
    } else if (has('animation', 'family', 'kids', 'children')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.FAMILY;
    } else if (has('comedy')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.COMEDY;
    } else if (has('thriller', 'suspense', 'crime', 'film-noir', 'film noir')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.THRILLER;
    } else if (has('romance')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.ROMANCE;
    } else if (has('documentary', 'sport', 'history', 'biography', 'music')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.SPECIAL_INTEREST;
    } else if (has('drama')) {
      pool = REVIEW_SNIPPETS_BY_GENRE.DRAMA;
    } else {
      // Default to Action or Drama if unmapped
      pool = REVIEW_SNIPPETS_BY_GENRE.DRAMA;
    }
  }

  const index = seed % pool.length;
  return pool[index];
}
